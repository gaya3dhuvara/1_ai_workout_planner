"""Default workout plans for fallback when Groq API fails.

The module provides a simple deterministic generator that creates a plan based on
the user's selections.  It covers *all* possible combinations of:

- fitness goal (4 options)
- experience level (3 options)
- days per week (1‑7)
- equipment access (any subset of the three options)

Rather than store a gigantic hard‑coded dictionary, we generate a readable plan
on the fly using straightforward rules.  This keeps the file small while still
fulfilling the requirement of having a *separate* source of default plans.
"""

from typing import Dict, List

# Simple exercise pools
STRENGTH_EXERCISES = {
    "no equipment": ["Bodyweight squats", "Push‑ups", "Lunges", "Plank"],
    "home dumbbells": ["Dumbbell goblet squat", "Dumbbell bench press", "Dumbbell rows", "Dumbbell lunges"],
    "full gym": ["Barbell back squat", "Deadlift", "Bench press", "Lat pulldown"],
}

CARDIO_EXERCISES = [
    "Jump rope (5 min)",
    "Running or brisk walk (20 min)",
    "Cycling (15 min)",
    "Burpees (3 sets of 10)",
]

ENDURANCE_EXERCISES = [
    "Interval running (30 sec sprint / 90 sec jog x 8)",
    "Rowing machine (20 min)",
    "Stair climber (15 min)",
]

def _select_exercises(equipment: List[str], goal: str) -> List[str]:
    """Return a list of exercises appropriate for the goal and equipment.
    """
    # Determine base pool
    if goal == "Build muscle":
        # prioritize strength
        pool = []
        for eq in equipment:
            pool.extend(STRENGTH_EXERCISES.get(eq.lower(), []))
        if not pool:
            pool = STRENGTH_EXERCISES["no equipment"]
        return pool[:4]
    if goal == "Lose fat":
        # mix cardio + some strength
        pool = []
        pool.extend(CARDIO_EXERCISES[:2])
        for eq in equipment:
            pool.extend(STRENGTH_EXERCISES.get(eq.lower(), []))
        return pool[:4]
    if goal == "Improve endurance":
        pool = ENDURANCE_EXERCISES[:3]
        pool.extend(CARDIO_EXERCISES[:1])
        return pool[:4]
    # General fitness – balanced
    pool = []
    pool.extend(STRENGTH_EXERCISES.get(equipment[0].lower(), [])[:2])
    pool.extend(CARDIO_EXERCISES[:2])
    return pool[:4]

def get_default_plan(user_data: Dict[str, any]) -> str:
    """Generate a deterministic fallback plan based on the supplied user data.

    Parameters
    ----------
    user_data: dict
        Keys: ``goal``, ``experience``, ``days``, ``equipment`` (list), ``injuries`` (optional).
    """
    goal = user_data.get("goal", "General fitness")
    days = int(user_data.get("days", 3))
    equipment = user_data.get("equipment", ["No equipment"])
    injuries = user_data.get("injuries", "")
    if injuries is not None:
        injuries = injuries.lower()

    # Basic header
    lines = [f"# Default {goal} Plan – {days} day(s) per week", ""]
    exercises = _select_exercises(equipment, goal)

    # Simple injury-based filtering
    filtered = []
    for ex in exercises:
        lower = ex.lower()
        if injuries is not None and "knee" in injuries and any(k in lower for k in ["squat", "lung", "jump"]):
            continue
        if injuries is not None and "overhead" in injuries and "press" in lower:
            continue
        filtered.append(ex)
    if not filtered:
        filtered = exercises  # fallback if everything filtered out

    # Determine sets/reps based on goal
    def sets_reps(ex_name: str) -> tuple[int, str]:
        if ex_name.lower() in [e.lower() for e in CARDIO_EXERCISES]:
            return (1, "Duration: 20 min")
        if ex_name.lower() in [e.lower() for e in ENDURANCE_EXERCISES]:
            return (1, "Duration: 20 min")
        # strength default
        return (4, "10 reps")

    for d in range(1, days + 1):
        lines.append(f"## Day {d}")
        lines.append("")
        # Table header
        lines.append("| Exercise | Sets | Reps / Duration |")
        lines.append("|---|---|---|")
        for ex in filtered:
            s, r = sets_reps(ex)
            lines.append(f"| {ex} | {s} | {r} |")
        lines.append("")
        if injuries:
            lines.append("_Note: Adjust or skip any exercise that aggravates your injury._")
            lines.append("")
    lines.append("---")
    lines.append(
        "*Disclaimer*: This autogenerated plan is for informational purposes only and does not replace professional medical or fitness advice."
    )
    return "\n".join(lines)


